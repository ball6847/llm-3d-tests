/* =========================================================================
   Sync the bench collection with the result files on disk.

   The v1/ and v2/ folders are the source of truth. This script:
     1. scans them for *.html results
     2. regenerates manifest.js (the model list + byte sizes the pages read)
     3. captures thumbnails for any result that lacks one
     4. reports what was added, resized, or removed

   It never edits or deletes the result HTML files themselves.

   Run:
     node tools/sync-collection.mjs             add missing + capture new thumbs
     node tools/sync-collection.mjs --dry-run   report only, write nothing
     node tools/sync-collection.mjs --force     also re-capture every thumbnail
     node tools/sync-collection.mjs --prune     also delete orphaned thumbnails

   Env: CHROME_PATH  THUMB_W  THUMB_H
   ========================================================================= */

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { ROOT, launchBrowser, captureScene, scanScenes } from './capture.mjs';

const require = createRequire(import.meta.url);
const args = new Set(process.argv.slice(2));
const DRY = args.has('--dry-run');
const FORCE = args.has('--force');
const PRUNE = args.has('--prune');
const OUT = path.join(ROOT, 'thumbs');
const W = Number(process.env.THUMB_W || 960);
const H = Number(process.env.THUMB_H || 540);
const CONCURRENCY = 3;

/* ---- read the current manifest, if any ---- */
let existing = { 1: [], 2: [] };
try {
  const m = require(path.join(ROOT, 'manifest.js'));
  existing = { 1: m[1] || m['1'] || [], 2: m[2] || m['2'] || [] };
} catch { /* first run: no manifest yet */ }

const oldSlugs = { 1: new Set(existing[1].map((m) => m.slug)), 2: new Set(existing[2].map((m) => m.slug)) };
const oldBytes = {};
for (const v of [1, 2]) for (const m of existing[v]) oldBytes[`${v}/${m.slug}`] = m.bytes;

/* ---- scan disk ---- */
const jobs = scanScenes(fs);
const disk = { 1: [], 2: [] };
for (const j of jobs) disk[Number(j.v.slice(1))].push({ slug: j.slug, bytes: j.bytes });
for (const v of [1, 2]) disk[v].sort((a, b) => a.slug.localeCompare(b.slug));

const added = [], removed = [], resized = [];
for (const v of [1, 2]) {
  const now = new Set(disk[v].map((m) => m.slug));
  for (const m of disk[v]) {
    if (!oldSlugs[v].has(m.slug)) added.push(`${v === 1 ? 'v1' : 'v2'}/${m.slug}`);
    else if (oldBytes[`${v}/${m.slug}`] !== m.bytes) resized.push(`${v === 1 ? 'v1' : 'v2'}/${m.slug}`);
  }
  for (const s of oldSlugs[v]) if (!now.has(s)) removed.push(`${v === 1 ? 'v1' : 'v2'}/${s}`);
}

/* ---- thumbnails needed ---- */
fs.mkdirSync(OUT, { recursive: true });
const have = new Set(fs.readdirSync(OUT).filter((f) => f.endsWith('.png')));
const diskKeys = new Set(jobs.map((j) => `${j.v}-${j.slug}.png`));
const toCapture = jobs.filter((j) => FORCE || !have.has(`${j.v}-${j.slug}.png`));
const orphans = [...have].filter((f) => !diskKeys.has(f));

/* ---- report ---- */
console.log(`disk: v1=${disk[1].length} v2=${disk[2].length} (was v1=${existing[1].length} v2=${existing[2].length})`);
console.log(`added:   ${added.length ? added.join(', ') : 'none'}`);
console.log(`resized: ${resized.length ? resized.join(', ') : 'none'}`);
console.log(`removed: ${removed.length ? removed.join(', ') : 'none'}`);
console.log(`thumbs to capture: ${toCapture.length ? toCapture.map((j) => `${j.v}/${j.slug}`).join(', ') : 'none'}`);
if (orphans.length) console.log(`orphaned thumbs: ${orphans.join(', ')}${PRUNE ? ' (will delete)' : ' (use --prune to delete)'}`);

if (DRY) { console.log('\ndry run: nothing written.'); process.exit(0); }

/* ---- write manifest.js ---- */
const manifestBody =
  '/* Generated by tools/sync-collection.mjs from the files in v1/ and v2/.\n' +
  '   Do not edit by hand; re-run the sync script after adding or removing results. */\n' +
  'var BENCH_MANIFEST = ' + JSON.stringify({ 1: disk[1], 2: disk[2] }, null, 2) + ';\n' +
  'if (typeof window !== "undefined") window.MANIFEST = BENCH_MANIFEST;\n' +
  'if (typeof module !== "undefined" && module.exports) module.exports = BENCH_MANIFEST;\n';
fs.writeFileSync(path.join(ROOT, 'manifest.js'), manifestBody);
console.log('\nwrote manifest.js');

/* ---- prune orphans ---- */
if (PRUNE) for (const f of orphans) { fs.unlinkSync(path.join(OUT, f)); console.log(`pruned thumbs/${f}`); }

/* ---- capture ---- */
let failed = [];
if (toCapture.length) {
  const browser = await launchBrowser();
  let cursor = 0;
  async function worker() {
    while (cursor < toCapture.length) {
      const job = toCapture[cursor++];
      const r = await captureScene(browser, job, OUT, { width: W, height: H });
      if (r.ok) console.log(`ok   ${job.v}/${job.slug}`);
      else { failed.push(`${job.v}/${job.slug}: ${r.error}`); console.log(`FAIL ${job.v}/${job.slug}: ${r.error}`); }
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, () => worker()));
  await browser.close();
}

console.log(`\nsync done. ${toCapture.length - failed.length}/${toCapture.length} new thumbnails captured.`);
if (failed.length) { console.log(failed.join('\n')); process.exit(1); }